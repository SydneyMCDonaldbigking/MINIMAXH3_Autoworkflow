def build_sequence(cfg: dict) -> dict:
    slug = cfg["slug"]
    a = {k: asset_rel(cfg, k) for k in KINDS}
    product = product_rel(cfg)
    logo = "../company_logo/AGO.png"
    return {
        "sequence_id": f"{slug}_3x5_native1080",
        "server": "http://127.0.0.1:8189",
        "defaults": {
            "mode": "r2v", "width": 1088, "height": 1920, "duration": 5.0,
            "steps": 8, "turbo": True, "turbo_low_vram": True, "no_audio": True,
            "ref_image_size": "match", "poll": 10, "timeout": 10800,
        },
        "clips": [
            {"id": "clip-01-prep-to-heat",
             "prompt_file": f"../prompts/h3_3x5_1080/{slug}_clip_01.md",
             "ref_images": [a["character_scene"], a["prep_state"], a["cook_state"],
                            a["hero_state"], product, logo],
             "seed": cfg["seed_base"] + 1,
             "prefix": f"sequence/{slug}_3x5_native1080/clip-01"},
            {"id": "clip-02-cook",
             "prompt_file": f"../prompts/h3_3x5_1080/{slug}_clip_02.md",
             "use_previous_last_frame_as_ref": True,
             "ref_images": [a["character_scene"], a["prep_state"], a["cook_state"],
                            a["hero_state"], product],
             "seed": cfg["seed_base"] + 2,
             "prefix": f"sequence/{slug}_3x5_native1080/clip-02"},
            {"id": "clip-03-serving-hero",
             "prompt_file": f"../prompts/h3_3x5_1080/{slug}_clip_03.md",
             "use_previous_last_frame_as_ref": True,
             "ref_images": [a["character_scene"], a["cook_state"],
                            a["hero_state"], product, logo],
             "seed": cfg["seed_base"] + 3,
             "prefix": f"sequence/{slug}_3x5_native1080/clip-03"},
        ],
        "final": {
            "filename": f"{slug}_3x5_native_1080x1920.mp4",
            "concat_mode": "both",
            "crop": {"width": 1080, "height": 1920, "x": 4, "y": 0},
            "crf": 16, "preset": "medium", "keep_audio": False,
        },
    }


def check_rendered_prompts(cfg: dict) -> list[tuple[str, list[str]]]:
    """Render prompts without writing production files, then run the validator."""
    from prompts.validate_prompt import check, refs_for_clip

    seq = build_sequence(cfg)
    funcs = ((1, clip01), (2, clip02), (3, clip03))
    failures: list[tuple[str, list[str]]] = []
    with tempfile.TemporaryDirectory() as tmp:
        tmp_dir = pathlib.Path(tmp)
        for index, (n, fn) in enumerate(funcs):
            path = tmp_dir / f"{cfg['slug']}_clip_0{n}.md"
            path.write_text(fn(cfg), encoding="utf-8", newline="\n")
            problems = check(path, refs_for_clip(seq["clips"][index]))
            if problems:
                failures.append((path.name, problems))
    return failures


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    parser.add_argument("slugs", nargs="*")
    parser.add_argument("--all", action="store_true")
    parser.add_argument("--check", action="store_true",
                        help="render to a temporary directory and validate without writing output files")
    args = parser.parse_args(argv)

    available = sorted(p.stem for p in CONFIG_DIR.glob("*.json"))
    slugs = available if args.all else args.slugs
    if not slugs:
        parser.error("name a dish, or use --all")

    if args.check:
        failed = 0
        for slug in slugs:
            cfg = json.loads((CONFIG_DIR / f"{slug}.json").read_text(encoding="utf-8"))
            label = f"{cfg['slug']} ({cfg['dish_en']})"
            failures = check_rendered_prompts(cfg)
            if not failures:
                print(f"  ok   {label}: rendered prompts validate")
                continue
            failed += 1
            print(f"  FAIL {label}")
            for name, problems in failures:
                print(f"       {name}")
                for problem in problems:
                    print(f"         ! {problem}")
        return 1 if failed else 0

    PROMPT_DIR.mkdir(parents=True, exist_ok=True)
    for slug in slugs:
        cfg = json.loads((CONFIG_DIR / f"{slug}.json").read_text(encoding="utf-8"))
        for n, fn in ((1, clip01), (2, clip02), (3, clip03)):
            path = PROMPT_DIR / f"{slug}_clip_0{n}.md"
            path.write_text(fn(cfg), encoding="utf-8", newline="\n")
        seq_path = SEQ_DIR / f"{slug}_3x5_1080.json"
        seq_path.write_text(json.dumps(build_sequence(cfg), ensure_ascii=False, indent=2) + "\n",
                            encoding="utf-8", newline="\n")
        print(f"  {cfg['slug']}: 3 prompts + {seq_path.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
