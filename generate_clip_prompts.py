#!/usr/bin/env python3
"""
Generate the three Ref2VA clip prompts and the sequence JSON for a dish.

For any new dish config, first build the recipe-grounded package described in
prompts/COOKING_PROMPT_PRODUCTION_STANDARD.md. Do not create dish configs from
memory when real recipe steps, temperatures, textures, and doneness matter.

The three-shot shape here is not a guess. It is the one that measured 2.5%,
0.0% and 0.8% camera flip rates on the beef, kelp and tomato ads, against 33.6%
for the version that preceded it. Every rule it encodes was paid for:

  shot 1  wide establishing, one committed continuous push, ends on the
          ingredients being readable
  shot 2  medium over the work surface, locked off, one gathering action, the
          knife explicitly at rest. Never a tight close-up of a hand working a
          tool: at 4 steps that produced a knife in two pieces and a cabbage
          that changed species, and 8 steps improved it without curing it
  shot 3  locked close-up, one continuous action carried to a physical endpoint.
          Never a state to hold; the beat that ended on "steam rises" left the
          model 40 frames of nothing and it filled them with 45% frame-to-frame
          direction reversals

Reference binding is positional and clips 2 and 3 shift by one, because the
sequence runner prepends the previous clip's last frame. Getting that wrong
produces a plausible-looking clip with every reference attached to the wrong
thing, so the sequence is generated here too rather than written by hand.

Usage:
  python generate_clip_prompts.py --all
  python generate_clip_prompts.py --all --check
  python generate_clip_prompts.py kungpao_chicken
"""

from __future__ import annotations

import argparse
