import tempfile

ROOT = pathlib.Path(__file__).resolve().parent
CONFIG_DIR = ROOT / "prompts" / "dish_configs"
PROMPT_DIR = ROOT / "prompts" / "h3_3x5_1080"
SEQ_DIR = ROOT / "sequences"
ASSET_DIRS = {p.name.split("_", 1)[1]: p for p in (ROOT / "outputs" / "reference_assets").iterdir()
              if p.is_dir()} if (ROOT / "outputs" / "reference_assets").is_dir() else {}

KINDS = ["character_scene", "prep_state", "cook_state", "hero_state"]

NEG_COMMON = ("distorted faces, extra fingers, invented text, captions, watermarks, "
              "floating logos, camera shake, and scene jumps")


def asset_rel(cfg: dict, kind: str) -> str:
    """Path to a generated reference, relative to sequences/.

    Assets generated by generate_dish_assets.py are named {slug}_{kind}.png. The
    two dishes that predate that script are not, so a config may name its files
    explicitly in "assets" rather than have them renamed out from under the
    sequences that already reference them.
    """
    name = cfg.get("assets", {}).get(kind, f"{cfg['slug']}_{kind}") + ".png"
    for group in (ROOT / "outputs" / "reference_assets").iterdir():
        candidate = group / name
        if candidate.is_file():
            return "../" + candidate.relative_to(ROOT).as_posix()
    raise SystemExit(f"reference not found: {name}")


def subject2(cfg: dict) -> str:
    """The <Subject 2> definition line, for dishes with a second person in frame."""
    return f"\n<Subject 2> is {cfg['cook2']}." if cfg.get("cook2") else ""


def fully_preserved2(cfg: dict) -> str:
    """The <Subject 2> retention line. Every marker must name every subject."""
    return ("\n<Subject 2>: fully_preserved. Same face, build and clothing throughout, "
            "and never handling anything hot.") if cfg.get("cook2") else ""


def product_rel(cfg: dict) -> str:
    p = ROOT / "sample_pictures" / cfg["product_dir"] / cfg["product_file"]
    if not p.is_file():
        raise SystemExit(f"product image not found: {p}")
    return "../" + p.relative_to(ROOT).as_posix()


def beat(cfg: dict, key: str, default: str) -> str:
    """The action inside a shot, which the recipe decides.

    The camera grammar around it does not move: shot 1 of a clip establishes,
    shot 2 carries the single committed push, shot 3 locks off and ends on a
    physical stop. Those measured 2.5%, 0.0% and 0.8% flip rates and are not
    a dish's business. What happens in front of the lens is.

    The generic defaults describe a stir-fry, because that is what the first six
    dishes were. They are wrong for a dish that is simmered for an hour, or one
    that is fried, drained and then tossed. A config supplies "beats" to say what
    its recipe actually does; anything it omits falls back to the generic beat.
    """
    return (cfg.get("beats") or {}).get(key) or default


def clip01(cfg: dict) -> str:
    c = cfg
    # Overridable because the default beat tips an ingredient into a vessel, and a
    # tray of egg tarts is placed, not tipped.
    c1s3 = beat(c, "c1s3",
                "The hands of <Subject 1> enter from the top of frame carrying the ingredient, "
                "tip it in once, and withdraw straight up out of frame empty.")
    # <Picture 3> is the working state, so the photograph shows the vessel FULL of a
    # nearly finished dish. Pointing the model at it and saying "the vessel, already
    # hot" got a wok of finished food with raw mince being tipped onto it - the
    # reference beat the wording, the same way the product photo's label did. The
    # vessel's starting state now has to be stated positively, and <Picture 3> is
    # explicitly reduced to the vessel itself for this shot.
    vessel_start = c.get("vessel_start", "empty and already hot, with nothing in it yet")
